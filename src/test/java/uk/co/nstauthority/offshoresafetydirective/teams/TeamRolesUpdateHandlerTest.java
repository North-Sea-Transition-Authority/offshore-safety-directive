import uk.co.nstauthority.offshoresafetydirective.energyportal.WebUserAccountId;
import uk.co.nstauthority.offshoresafetydirective.energyportal.user.EnergyPortalUserDtoTestUtil;
import uk.co.nstauthority.offshoresafetydirective.energyportal.user.EnergyPortalUserService;
import uk.co.nstauthority.offshoresafetydirective.teams.management.TeamManagementService;


@ExtendWith(MockitoExtension.class)
class TeamRolesUpdateHandlerTest {

  private static final String SERVICE_NAME = "service-name";
  private static final UUID TEAM_ID = UUID.randomUUID();
  private static final Long USER_WUA_ID = 1L;
  private static final Long INVOKING_USER_WUA_ID = 2L;
  private static final ServiceProviderUserTeamRolesDto SERVICE_PROVIDER_USER_TEAM_ROLES_DTO = new ServiceProviderUserTeamRolesDto(
      USER_WUA_ID,
      TEAM_ID.toString(),
      "teamType",
      Set.of(Role.TEAM_MANAGER.name())
  );

  @Mock
  private EnergyPortalUserService energyPortalUserService;

  @Mock
  private TeamManagementService teamManagementService;

  private final EnergyPortalAccountsConfigurationProperties configurationProperties
      = new EnergyPortalAccountsConfigurationProperties(
          SERVICE_NAME,
      "dev1",
      false,
      false,
      null,
      null
  );

  private TeamRolesUpdateHandler teamRolesUpdateHandler;

  private ServiceProviderTeamRolesEpasMessage message;

  @BeforeEach
  void setUp() {
    teamRolesUpdateHandler = new TeamRolesUpdateHandler(
        energyPortalUserService,
        teamManagementService,
        configurationProperties
    );

    message = new ServiceProviderTeamRolesEpasMessage(
        SERVICE_NAME,
        "correlationId",
        Instant.now(),
        SERVICE_PROVIDER_USER_TEAM_ROLES_DTO,
        INVOKING_USER_WUA_ID
    );
  }

  @Test
  void accept_whenMessageNotForService_thenDoNothing() {
    message.setService("different-service");

    teamRolesUpdateHandler.accept(message);

    verify(teamManagementService, never()).setUserTeamRoles(anyLong(), any(), any());
  }

  @Test
  void accept_whenInvalidTeam_thenDoNothing() {
    when(teamManagementService.getTeam(TEAM_ID)).thenReturn(Optional.empty());

    teamRolesUpdateHandler.accept(message);

    verify(teamManagementService, never()).setUserTeamRoles(anyLong(), any(), any());
  }

  @Test
  void accept_whenValidMessage_thenUpdateTeamRoles() {
    var team = TeamTestUtil.newBuilder().build();
    when(teamManagementService.getTeam(TEAM_ID)).thenReturn(Optional.of(team));

    var invokingUserEnergyEnergyPortalUserDto = EnergyPortalUserDtoTestUtil.Builder().build();
    when(energyPortalUserService.findByWuaId(
        refEq(WebUserAccountId.valueOf(String.valueOf(INVOKING_USER_WUA_ID))),
        eq(new RequestPurpose("Audit who updated user roles"))
    ))
        .thenReturn(Optional.of(invokingUserEnergyEnergyPortalUserDto));

    // Verify that the call to teamManagementService is wrapped in withFallbackAuditUser,
    // so that the audit revisions generated by setting the roles have the correct associating wuaIds.
    doAnswer(invocation -> {
      assertThat(AuditRevisionUtil.getFallbackAuditUser())
          .usingRecursiveComparison()
          .isEqualTo(ServiceUserDetail.from(invokingUserEnergyEnergyPortalUserDto));
      return null;
    }).when(teamManagementService).setUserTeamRoles(anyLong(), any(), any());

    teamRolesUpdateHandler.accept(message);

    verify(teamManagementService).setUserTeamRoles(
        USER_WUA_ID,
        team,
        List.of(Role.TEAM_MANAGER)
    );
  }
}